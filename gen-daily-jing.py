    punct_cov = 0
    for r in parse_draft():
        title = dz_titles.get(r['kr'])
        if not title:
            sys.exit('%s 不在全藏索引内' % r['kr'])
        if '/' in title:
            title = title.split('/')[-1]
        units, has_punct = sub_units(r['kr'], title, r['units'], r['reason'])
        punct_cov += 1 if has_punct else 0
        per_text.append(units)
    pool = []
    max_u = max(len(u) for u in per_text)
    for rr in range(max_u):
        for units in per_text:
            if rr < len(units):
                pool.append(units[rr])
    print('sub pool: %d texts, %d units, punct coverage %d/%d'
          % (len(per_text), len(pool), punct_cov, len(per_text)))
    return pool


