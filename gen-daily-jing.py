def load_jing(path):
    with open(path, encoding='utf-8') as f:
        txt = f.read()
    i = txt.index('] = ') + 4
    j = txt.rindex('}')
    return json.loads(txt[i:j + 1])


def main():
    with open(FEED_INDEX, encoding='utf-8') as f:
        feed = json.load(f)
    titles = {x['id']: x['title'] for x in feed['index']}
    common = [x['id'] for x in feed['index'] if x['id'] not in NEIDAN]
    if len(common) != 29:
        sys.exit('常见经文应为 29 部，实得 %d' % len(common))

    per_text = []  # [(sid, [unit,...])]
    for sid in common:
        d = load_jing(os.path.join(JING_DIR, sid + '.js'))
        glosses = GLOSS.get(sid)
        if glosses is None:
            sys.exit('%s 缺题解表' % sid)
        secs = d['sections']
        if len(glosses) != len(secs):
            sys.exit('%s 题解数 %d != 节数 %d' % (sid, len(glosses), len(secs)))
        title = titles.get(sid) or d['title']
        units = []
        for n, sec in enumerate(secs):
            chars = sum(len(p if isinstance(p, str) else (p.get('t') or ''))
                        for p in sec['paras'])
            h = (sec.get('h') or '').strip()
            if h == '全文' or h == d['title'] or h == title:
                h = ''
            units.append({'s': sid, 't': title, 'n': n, 'h': h,
                          'g': glosses[n], 'c': chars,
                          'm': max(1, int(round(chars / 300.0)))})
        per_text.append(units)

    # 主池跨部交错：第 r 轮取各部第 r 节
    main_pool = []
    max_sec = max(len(u) for u in per_text)
    for r in range(max_sec):
        for units in per_text:
            if r < len(units):
                main_pool.append(units[r])
    if len(main_pool) != 296:
        sys.exit('主池应为 296 单位，实得 %d' % len(main_pool))

    sub_pool = build_sub_pool()

    # 公平合并：按已出比例轮转，两池单位均匀散布整个轮换周期
    pool = []
    ia = ib = 0
    while ia < len(main_pool) or ib < len(sub_pool):
        if ib >= len(sub_pool) or (ia < len(main_pool)
                                   and ia / len(main_pool) <= ib / len(sub_pool)):
            pool.append(main_pool[ia])
            ia += 1
        else:
            pool.append(sub_pool[ib])
            ib += 1
    keys = [(u['s'], u['n'], u.get('p', 0)) for u in pool]
    if len(set(keys)) != len(keys):
        sys.exit('池内出现重复单位（同经同卷同段）')

    header = ('/* 每日一经轮换池（%d 个单位）：主池＝常见经文 29 部按节拆 %d 单位'
              '＋副池＝道藏全集正选 202 部按卷/段拆 %d 单位，两池交错合并轮换。\n'
              ' * 由 gen-daily-jing.py 机械生成（主池题解人工表、副池题解源出批准草案入选理由），勿手改本文件。\n'
              ' * 字段：s 经文id（sNN=精选 / KR5…=全藏） / t 经名 / n 卷节序（阅读器锚点） / h 卷章题 / g 题解 / c 字数 / m 预计分钟 / p 段锚（卷内内容字偏移，0 省略）。 */\n'
              % (len(pool), len(main_pool), len(sub_pool)))
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(header)
        f.write('window.DAILY_JING_POOL = ')
        f.write(json.dumps(pool, ensure_ascii=False, separators=(',', ':')))
        f.write(';\n')
    print('pool units:', len(pool), '->', OUT)


if __name__ == '__main__':
    main()
