def clen(t):
    """内容字数：剥标点/空白（与阅读器段锚口径一致）。"""
    return sum(1 for ch in t if ch not in STRIP_CHARS and not ch.isspace())


def sub_gloss(reason):
    keep = []
    for cl in reason.split('，'):
        cl = cl.strip()
        if not cl or '精选' in cl or cl.startswith('取'):
            continue
        keep.append(cl)
        if sum(len(x) for x in keep) >= 8:
            break
    if not keep:
        keep = [reason.split('，')[0].strip()]
    return '，'.join(keep)[:30]


def clean_vol_h(h, title):
    h = (h or '').strip()
    if title and h.startswith(title):
        h = h[len(title):].strip()
    m = re.search(r'[卷巻][之]?[一二三四五六七八九十百上下中]+', h)
    if m and m.start() >= 4:
        # 书名（或其异体）前缀＋卷次：只留卷次（其后的千字文叶码等注记一并截掉）
        h = m.group(0)
    else:
        m = re.search(r'第[一二三四五六七八九十百\d]+卷', h)
        if m and m.start() >= 4:
            h = m.group(0)
        else:
            for kw in ['目録', '目錄', '總目', '凡例', '序例']:
                if kw in h and len(h) > len(kw) + 3:
                    h = kw
                    break
    # 卷题后挂的校勘注（如「(二同/卷)温一」「（…）」）不是题面，截掉
    for junk in ['（', '(', '/', '　']:
        i = h.find(junk)
        if i > 0:
            h = h[:i]
    return h.strip()


def load_dz_vols(kr):
    """与阅读器同源同序：原文 volumes 为骨架，逐卷有标点则用标点段。"""
    with open(os.path.join(DZ_DIR, 'texts', kr + '.json'), encoding='utf-8') as f:
        w = json.load(f)
    pw = None
    pp = os.path.join(DZ_DIR, 'texts-punct', kr + '.json')
    if os.path.exists(pp):
        with open(pp, encoding='utf-8') as f:
            pw = json.load(f)
    vols = []
    for vi, v in enumerate(w['volumes']):
        paras = v['paras']
        if pw and pw.get('volumes') and vi < len(pw['volumes']) and pw['volumes'][vi]:
            paras = pw['volumes'][vi]['paras']
        vols.append({'h': v.get('h') or '', 'paras': paras})
    return vols, bool(pw)


def sub_units(kr, title, target, reason):
    """按草案「拟拆单位数」落实到卷/段锚点：
    1 单位=整部；单位数=卷数→逐卷；单位数<卷数→均匀取卷（含首尾卷）；
    单位数>卷数→全书按段内容字累计均分切段（段锚 p）。"""
    vols, has_punct = load_dz_vols(kr)
    V = len(vols)
    gloss = sub_gloss(reason)

    def raw_chars(paras):
        return sum(len(t) for t in paras)

    units = []
    if target == 1:
        units.append({'s': kr, 't': title, 'n': 0, 'h': '', 'g': gloss,
                      'c': sum(raw_chars(v['paras']) for v in vols)})
    elif target == V:
        for vi, v in enumerate(vols):
            units.append({'s': kr, 't': title, 'n': vi,
                          'h': clean_vol_h(v['h'], title), 'g': gloss,
                          'c': raw_chars(v['paras'])})
    elif target < V:
        idxs = []
        for i in range(target):
            x = int(i * (V - 1) / (target - 1) + 0.5)
            if x not in idxs:
                idxs.append(x)
        vi = 0
        while len(idxs) < target and vi < V:
            if vi not in idxs:
                idxs.append(vi)
            vi += 1
        idxs.sort()
        if len(idxs) != target:
            sys.exit('%s 取卷失败：拟 %d 卷实取 %d' % (kr, target, len(idxs)))
        for vi in idxs:
            v = vols[vi]
            units.append({'s': kr, 't': title, 'n': vi,
                          'h': clean_vol_h(v['h'], title), 'g': gloss,
                          'c': raw_chars(v['paras'])})
    else:
        flat = []  # (vi, 内容字数, 原始字数, 该段在本卷内的内容字前置偏移)
        for vi, v in enumerate(vols):
            acc = 0
            for t in v['paras']:
                flat.append((vi, clen(t), len(t), acc))
                acc += clen(t)
        total_c = sum(f[1] for f in flat)
        starts = [0]
        acc = 0
        fi = 0
        for k in range(1, target):
            want = total_c * k / target
            while fi < len(flat) and acc + flat[fi][1] < want:
                acc += flat[fi][1]
                fi += 1
            st = fi
            if st <= starts[-1]:
                st = starts[-1] + 1
            if st >= len(flat):
                sys.exit('%s 切段越界（拟 %d 段）' % (kr, target))
            starts.append(st)
        for ci, st in enumerate(starts):
            en = starts[ci + 1] if ci + 1 < len(starts) else len(flat)
            if en <= st:
                sys.exit('%s 切出空段' % kr)
            vi0 = flat[st][0]
            units.append({'s': kr, 't': title, 'n': vi0,
                          'h': clean_vol_h(vols[vi0]['h'], title), 'g': gloss,
                          'c': sum(f[2] for f in flat[st:en]),
                          '_p': flat[st][3]})
    if len(units) != target:
        sys.exit('%s 拟拆 %d 单位，实得 %d' % (kr, target, len(units)))
    # 整部只有卷内分段且卷题为空（如单卷本卷题与书名同）：按段序标其一/其二
    if len(units) > 1 and all(not u['h'] for u in units):
        for k, u in enumerate(units):
            u['h'] = '其' + (CN_NUM[k] if k < 10 else str(k + 1))
    seen = {}
    for u in units:
        if u['h']:
            seen[u['h']] = seen.get(u['h'], 0) + 1
    cnt = {}
    for u in units:
        p = u.pop('_p', 0)
        if p:
            u['p'] = p
        u['m'] = max(1, int(round(u['c'] / 300.0)))
        if u['h'] and seen.get(u['h'], 0) > 1:
            k = cnt.get(u['h'], 0)
            cnt[u['h']] = k + 1
            u['h'] = u['h'] + '·其' + (CN_NUM[k] if k < 10 else str(k + 1))
    return units, has_punct


